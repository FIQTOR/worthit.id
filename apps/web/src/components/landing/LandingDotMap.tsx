interface LandingDotMapProps {
  selectedCityId: string;
}

export function LandingDotMap({ selectedCityId }: LandingDotMapProps) {
  const pulseRef = useRef<SVGCircleElement | null>(null);

  const coords = PINS[selectedCityId] || PINS.jakarta;

  return (
    <div className="hero-dot-map" aria-hidden="true">
      <svg viewBox="0 0 78 29" preserveAspectRatio="xMidYMid meet">
        {/* Background land dots */}
        {MAP_GRID.map((row, y) =>
          [...row].map((v, x) =>
            v === '1' ? (
              <circle key={`${x}-${y}`} cx={x + 0.5} cy={y + 0.5} r={0.27} />
            ) : null
          )
        )}

        {/* City Pins */}
        {Object.entries(PINS).map(([k, p]) => {
          const isSelected = k === selectedCityId;
          return (
            <circle
              key={k}
              className={`pin ${isSelected ? 'on' : ''}`}
              data-c={k}
              cx={p[0] + 0.5}
              cy={p[1] + 0.5}
              r={isSelected ? 0.75 : 0.42}
            />
          );
        })}

        {/* Pulse beacon on selected city */}
        <circle
          ref={pulseRef}
          cx={coords[0] + 0.5}
          cy={coords[1] + 0.5}
          r={1.2}
          fill="none"
          stroke="var(--ac)"
          strokeWidth={0.18}
          className="animate-ping"
          style={{ transformOrigin: `${coords[0] + 0.5}px ${coords[1] + 0.5}px` }}
        />
      </svg>
    </div>
  );
}
